#!/usr/bin/env python3
"""Pull public Credly badges into the site.

Writes data/credly.yaml (name, issuer, dates, verify URL) and the badge images
into assets/credly/<id>.png, so the page serves its own copies: nothing from
credly.com loads in a visitor's browser, the badges are plain outbound links.

    python3 tools/pull-credly.py [credly-user-slug]

Re-run after earning or renewing a badge, then rebuild with hugo.
"""
import json
import pathlib
import sys
import urllib.request

USER = sys.argv[1] if len(sys.argv) > 1 else "max-mccann"
ROOT = pathlib.Path(__file__).resolve().parent.parent
IMG_DIR = ROOT / "assets" / "credly"
DATA = ROOT / "data" / "credly.yaml"
UA = {"User-Agent": "maxdraco-site-build/1.0"}


def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=30) as r:
        return r.read()


def q(s):
    # YAML double-quoted scalar; json.dumps escaping is valid YAML.
    return json.dumps(s or "", ensure_ascii=False)


def main():
    badges, page = [], 1
    while True:
        d = json.loads(get(f"https://www.credly.com/users/{USER}/badges.json?page={page}&page_size=48"))
        badges += d["data"]
        if not d["metadata"].get("next_page_url"):
            break
        page += 1

    IMG_DIR.mkdir(parents=True, exist_ok=True)
    keep = set()
    lines = [f"# Generated by tools/pull-credly.py from credly.com/users/{USER}. Do not hand-edit.", "badges:"]
    for b in sorted(badges, key=lambda b: b.get("issued_at_date") or "", reverse=True):
        if b.get("state") not in (None, "accepted") or b.get("public") is False:
            continue
        t = b["badge_template"]
        issuer = ((t.get("issuer") or {}).get("entities") or [{}])[0].get("entity", {}).get("name") \
            or (t.get("issuer") or {}).get("summary", "").removeprefix("issued by ")
        img = f"{b['id']}.png"
        keep.add(img)
        (IMG_DIR / img).write_bytes(get(b.get("image_url") or t["image_url"]))
        lines += [
            f"  - id: {q(b['id'])}",
            f"    name: {q(t['name'])}",
            f"    issuer: {q(issuer)}",
            f"    issued: {q(b.get('issued_at_date'))}",
            f"    expires: {q(b.get('expires_at_date'))}",
            f"    url: {q('https://www.credly.com/badges/' + b['id'])}",
            f"    image: {q('credly/' + img)}",
        ]
    for old in IMG_DIR.glob("*.png"):
        if old.name not in keep:
            old.unlink()
    DATA.write_text("\n".join(lines) + "\n")
    print(f"{len(keep)} badges -> {DATA.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
